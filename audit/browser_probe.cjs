 await page.waitForTimeout(500);
 rows=(await api('GET','/infringements/')).data.items;
 record('Cross-origin popup messages cannot delete records',rows.some(x=>x.id===victim.id),{attackerOrigin:'http://localhost:3000',victimId:victim.id,exists:rows.some(x=>x.id===victim.id)});
 await attacker.close();
 // Simulate an actual failed save, then inspect whether the user's draft survives.
