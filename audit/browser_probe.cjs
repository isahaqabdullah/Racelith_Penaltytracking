 record('Kart search finds records beyond current page',!(await page.locator('body').innerText()).includes('No infringements found for kart #71'),{kart:71,existsInDatabase:(await api('GET','/infringements/?limit=1000')).data.items.some(x=>x.kart_number===71),visible:(await page.locator('tbody').last().innerText())});
