 await page.locator('#session-name').fill(sessionName);
 await page.getByRole('button',{name:'Create Session',exact:true}).click();await page.waitForTimeout(600);
 record('Create session through UI',(await page.locator('body').innerText()).includes(sessionName),sessionName);
 record('Dashboard renders and WebSocket connects',(await page.locator('body').innerText()).includes('Live'),await page.locator('body').innerText());
