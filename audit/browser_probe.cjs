 await page.getByRole('button',{name:'Qualifying: OFF',exact:true}).click();await page.waitForTimeout(250);
 await log('74','White Line Infringement');
 rows=(await api('GET','/infringements/')).data.items;
 record('Qualifying form assigns fastest lap invalidation',rows.find(x=>x.kart_number===74)?.penalty_description==='Fastest Lap Invalidation',rows.find(x=>x.kart_number===74));
 await page.getByRole('button',{name:'Qualifying: ON',exact:true}).click();
 const popPromise=context.waitForEvent('page');await page.getByRole('button',{name:'Open in new tab'}).click();const popup=await popPromise;await popup.waitForTimeout(700);
 record('Expanded log renders records',(await popup.locator('body').innerText()).includes('74'),await popup.locator('body').innerText());
