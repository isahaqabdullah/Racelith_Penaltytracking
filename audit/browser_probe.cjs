 const after=await page.locator('tbody').last().getByRole('row').first().innerText();
 const body=await page.locator('body').innerText();
 record('Live update respects selected page and page size',!after.includes('9999'),{before,after,footer:body.match(/Showing .* entries/)?.[0],page:body.match(/Page\n\d+\nof\n\d+/)?.[0],rowCount:await page.locator('tbody').last().getByRole('row').count()});
 await page.screenshot({path:path.join(out,'pagination-after.png'),fullPage:true});
 await page.getByRole('button',{name:'← Back to Sessions',exact:true}).click();
 let sessionRow=page.getByRole('row').filter({hasText:sessionName});
 // Exercise the supported anchor-download fallback; headless Chrome cannot operate native save pickers.
 await page.evaluate(()=>delete window.showSaveFilePicker);
 const downloadPromise=page.waitForEvent('download');await sessionRow.getByRole('button',{name:'Export',exact:true}).click();const download=await downloadPromise;
 await download.saveAs(path.join(out,'browser-export.xlsx'));
 record('UI export fallback downloads workbook',!await download.failure(),{filename:download.suggestedFilename(),bytes:fs.statSync(path.join(out,'browser-export.xlsx')).size});
 const importName='Browser Imported '+Date.now();
 const csv=fs.readFileSync(path.join(out,'export.csv'),'utf8').replace('Name,Audit Main','Name,'+importName);
 fs.writeFileSync(path.join(out,'browser-import.csv'),csv);
 page.once('dialog',d=>d.accept());
 await page.getByRole('button',{name:'Import',exact:true}).click();await page.locator('#import-file').setInputFiles(path.join(out,'browser-import.csv'));
 await page.getByRole('button',{name:'Import Session',exact:true}).click();await page.waitForTimeout(600);
 record('UI imports CSV and navigates to imported session',(await page.locator('body').innerText()).includes(importName),{name:importName,sessions:(await api('GET','/session/')).data.sessions});
 await page.getByRole('button',{name:'← Back to Sessions',exact:true}).click();
 sessionRow=page.getByRole('row').filter({hasText:sessionName});
 await sessionRow.getByRole('button',{name:'Load',exact:true}).click();await page.waitForTimeout(500);
 record('UI loads existing session',(await page.locator('body').innerText()).includes(sessionName),sessionName);
 await page.getByRole('button',{name:'← Back to Sessions',exact:true}).click();
 sessionRow=page.getByRole('row').filter({hasText:importName});await sessionRow.locator('button').last().click();
